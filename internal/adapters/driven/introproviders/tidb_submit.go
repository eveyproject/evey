// TIDBSubmitter posts community-validated segments back to TheIntroDB so
// other Evey instances (and other media-server software) can benefit from
// our local detection results.
//
// Use NewTIDBContributor to get an implementation of domainlibrary.SegmentContributor
// that bundles this submitter with an AncestorResolver.
type TIDBSubmitter struct {
	baseURL    string
	apiKey     string
	httpClient *http.Client
}

// NewTIDBSubmitter returns a raw submitter for use in tests or when the caller
// already has a resolved Lookup. For production use, prefer NewTIDBContributor.
func NewTIDBSubmitter(apiKey string) *TIDBSubmitter {
	return &TIDBSubmitter{
		baseURL:    "https://api.theintrodb.org/v2",
		apiKey:     apiKey,
		httpClient: &http.Client{Timeout: 10 * time.Second},
	}
}

// WithTIDBSubmitterBaseURL overrides the API endpoint for tests.
func (s *TIDBSubmitter) WithBaseURL(u string) *TIDBSubmitter {
	s.baseURL = strings.TrimRight(u, "/")
	return s
}

type tidbSubmitRequest struct {
	SegmentType string  `json:"segment_type"`
	TmdbID      int     `json:"tmdb_id"`
	Season      int     `json:"season,omitempty"`
	Episode     int     `json:"episode,omitempty"`
	StartSec    float64 `json:"start_sec"`
	EndSec      float64 `json:"end_sec"`
}

// Submit sends one segment to TIDB POST /v2/submit. Returns nil immediately
// on skip conditions (no key, preview type) so callers need no prechecks.
func (s *TIDBSubmitter) Submit(ctx context.Context, segType string, lookup Lookup, startMs, endMs int64) error {
	ctx, span := tracing.StartSpan(ctx, "introproviders.tidb.Submit")
	defer span.End()

	if s.apiKey == "" {
		return nil // anonymous submissions are not supported by the API
	}
	if segType == "preview" {
		return nil // preview reels are auto-generated by TIDB, not community-submitted
	}

	// Map local type names to the TIDB vocabulary.
	apiType := segType
	if segType == "end_credits" {
		apiType = "outro"
	}

	body := tidbSubmitRequest{
		SegmentType: apiType,
		TmdbID:      lookup.TmdbID,
		Season:      lookup.Season,
		Episode:     lookup.Episode,
		StartSec:    float64(startMs) / 1000.0,
		EndSec:      float64(endMs) / 1000.0,
	}

	raw, err := json.Marshal(body)
	if err != nil {
		return fmt.Errorf("tidb submit: marshal body: %w", err)
	}

	req, err := http.NewRequestWithContext(ctx, http.MethodPost, s.baseURL+"/submit", bytes.NewReader(raw))
	if err != nil {
		return fmt.Errorf("tidb submit: build request: %w", err)
	}
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Authorization", "Bearer "+s.apiKey)

	resp, err := s.httpClient.Do(req)
	if err != nil {
		return fmt.Errorf("tidb submit: http: %w", err)
	}
	defer func() { _ = resp.Body.Close() }()

	if resp.StatusCode >= 400 {
		b, _ := io.ReadAll(io.LimitReader(resp.Body, 256))
		return fmt.Errorf("tidb submit: unexpected status %d: %s", resp.StatusCode, strings.TrimSpace(string(b)))
	}

	slog.Debug("tidb_submit: ok",
		slog.String("type", segType),
		slog.Int("tmdb_id", lookup.TmdbID),
		slog.Int("season", lookup.Season),
		slog.Int("episode", lookup.Episode))
	return nil
}

// TIDBContributor implements domainlibrary.SegmentContributor by resolving the
// series-level tmdb_id via AncestorResolver and delegating to TIDBSubmitter.
type TIDBContributor struct {
	submitter *TIDBSubmitter
	resolver  *AncestorResolver
}

// NewTIDBContributor wires a submitter and an ancestor resolver into the
// SegmentContributor port. resolver is the same instance already used by the
// cache layer - share it to avoid duplicating the repo reference.
func NewTIDBContributor(submitter *TIDBSubmitter, resolver *AncestorResolver) *TIDBContributor {
	return &TIDBContributor{submitter: submitter, resolver: resolver}
}

// Contribute implements domainlibrary.SegmentContributor. It resolves the
// episode's series tmdb_id and posts the segment to TIDB.
func (c *TIDBContributor) Contribute(ctx context.Context, item *domainlibrary.MediaItem, seg domainlibrary.MediaSegment) error {
	ctx, span := tracing.StartSpan(ctx, "introproviders.tidb.Contribute")
	defer span.End()

	lookup, err := c.resolver.Resolve(ctx, item)
	if err != nil {
		if isUnresolvable(err) {
			return nil // can't determine tmdb_id, skip silently
		}
		return fmt.Errorf("tidb contribute: resolve: %w", err)
	}
	return c.submitter.Submit(ctx, seg.Type, lookup, seg.StartMs, seg.EndMs)
}

func isUnresolvable(err error) bool {
	return err != nil && err.Error() == ErrLookupUnresolvable.Error()
}
