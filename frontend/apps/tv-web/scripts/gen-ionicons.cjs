// Regenerates src/components/ionicons.ts from the Android television's font.
// `npm i --prefix /tmp/otf opentype.js@1.3.4 && NODE_PATH=/tmp/otf/node_modules node scripts/gen-ionicons.cjs`
const fs = require("fs");
const path = require("path");
const opentype = require("opentype.js");

const root = path.resolve(__dirname, "..");
const vendor = path.resolve(root, "../../node_modules/@expo/vector-icons/build/vendor/react-native-vector-icons");
const font = opentype.loadSync(path.join(vendor, "Fonts/Ionicons.ttf"));
const glyphs = JSON.parse(fs.readFileSync(path.join(vendor, "glyphmaps/Ionicons.json"), "utf8"));
const out = path.join(root, "src/components/ionicons.ts");

const names = new Set();
const walk = (dir) => {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.tsx?$/.test(e.name) && !/\.test\./.test(e.name) && p !== out) {
      for (const m of fs.readFileSync(p, "utf8").matchAll(/"([a-z0-9-]+)"/g)) if (glyphs[m[1]]) names.add(m[1]);
    }
  }
};
walk(path.join(root, "src"));

let ts = "// Generated by scripts/gen-ionicons.cjs from the Ionicons font of @expo/vector-icons\n// (the Android television's icons): outlines, so no font is downloaded. viewBox 0 0 512 512.\nexport const IONICONS = {\n";
for (const n of [...names].sort()) {
  ts += `  "${n}": "${font.charToGlyph(String.fromCodePoint(glyphs[n])).getPath(0, 448, 512).toPathData(0)}",\n`;
}
ts += "} as const;\n\nexport type IoniconName = keyof typeof IONICONS;\n";
fs.writeFileSync(out, ts);
console.log(`${names.size} glyphs -> ${path.relative(root, out)}`);
