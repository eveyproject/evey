// themeCSS renders a theme's :root block. Kept deterministic (VAR_ORDER) so the
// generated file is stable and diffable.
export function themeCSS(name: ThemeCSSName, title: string): string {
  const vars = themeVars[name];
  const body = VAR_ORDER.map((v) => `  ${v}: ${vars[v]};`).join("\n");
  return `/* Evey - ${title} (generated from themeVars.ts - do not edit) */\n:root {\n${body}\n}\n`;
}

