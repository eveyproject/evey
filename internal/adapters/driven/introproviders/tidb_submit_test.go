package introproviders

import (
	"context"
	"encoding/json"
	"net/http"
	"net/http/httptest"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

// The submitter must POST a correctly-shaped JSON body and include the Bearer
// token in the Authorization header.
func TestTIDBSubmit_OK(t *testing.T) {
	t.Parallel()
	var got tidbSubmitRequest
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		assert.Equal(t, http.MethodPost, r.Method)
		assert.Equal(t, "/submit", r.URL.Path)
		assert.Equal(t, "Bearer test-key", r.Header.Get("Authorization"))
		assert.Equal(t, "application/json", r.Header.Get("Content-Type"))

		require.NoError(t, json.NewDecoder(r.Body).Decode(&got))
		w.WriteHeader(http.StatusOK)
	}))
	defer srv.Close()

	s := NewTIDBSubmitter("test-key").WithBaseURL(srv.URL)
	lookup := Lookup{TmdbID: 1396, Season: 1, Episode: 5}
	err := s.Submit(context.Background(), "intro", lookup, 30_000, 90_000)

	require.NoError(t, err)
	assert.Equal(t, "intro", got.SegmentType)
	assert.Equal(t, 1396, got.TmdbID)
	assert.Equal(t, 1, got.Season)
	assert.Equal(t, 5, got.Episode)
	assert.InDelta(t, 30.0, got.StartSec, 0.001)
	assert.InDelta(t, 90.0, got.EndSec, 0.001)
}

// end_credits must be mapped to "outro" in the TIDB vocabulary.
func TestTIDBSubmit_EndCreditsType_MappedToOutro(t *testing.T) {
	t.Parallel()
	var got tidbSubmitRequest
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		_ = json.NewDecoder(r.Body).Decode(&got)
		w.WriteHeader(http.StatusOK)
	}))
	defer srv.Close()

	s := NewTIDBSubmitter("key").WithBaseURL(srv.URL)
	require.NoError(t, s.Submit(context.Background(), "end_credits", Lookup{TmdbID: 1}, 0, 60_000))
	assert.Equal(t, "outro", got.SegmentType)
}

// Without an API key the submitter must skip silently (return nil without making any HTTP call).
func TestTIDBSubmit_NoKey_Skips(t *testing.T) {
	t.Parallel()
	called := false
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		called = true
	}))
	defer srv.Close()

	s := NewTIDBSubmitter("").WithBaseURL(srv.URL)
	err := s.Submit(context.Background(), "intro", Lookup{TmdbID: 1}, 0, 60_000)
	require.NoError(t, err)
	assert.False(t, called, "no HTTP call should be made when apiKey is empty")
}

