// Deterministic pseudo-random helpers shared by the selection/roulette
// services. No dependency on Math.random() so every consumer stays a pure,
// seed-reproducible function - a requirement for testing the "wow" roulette
// moment without flakiness.

// mulberry32: tiny, fast, good-enough distribution for cosmetic randomness.
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return function next(): number {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// FNV-1a: stable string -> uint32 hash, used to derive a numeric seed from an
// id or to pick a deterministic placeholder color per media item.
export function hashString(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

// Fisher-Yates shuffle driven by an injected rng, in place, returning the
// same array reference for convenience at call sites.
export function shuffleInPlace<T>(arr: T[], rng: () => number): T[] {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    const tmp = arr[i];
    arr[i] = arr[j];
    arr[j] = tmp;
  }
  return arr;
}
